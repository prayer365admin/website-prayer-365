export type SiteMessageKey = keyof (typeof SITE_MESSAGES)['en']

export type SiteT = (key: SiteMessageKey, vars?: Record<string, string | number>) => string

/**
 * Locale string, falling back to English (et/sv/fi ship English until the
 * translations land), then to the key. `{name}` placeholders take `vars`.
 * Plain function: usable from server components (siteT) and the client hook.
 */
export const translate = (
  locale: SiteLocale,
  key: SiteMessageKey,
  vars?: Record<string, string | number>,
) => {
  const text =
    (SITE_MESSAGES[locale] as Record<string, string>)[key] ?? SITE_MESSAGES.en[key] ?? key
  return vars ? text.replace(/\{(\w+)\}/g, (m, name) => String(vars[name] ?? m)) : text
}

/** `t` for server components: `const t = siteT(await getSiteLocale())`. */
export const siteT =
  (locale: SiteLocale): SiteT =>
  (key, vars) =>
    translate(locale, key, vars)
