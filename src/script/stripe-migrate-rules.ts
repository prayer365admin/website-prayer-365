/*
 * Pure rules for the Stripe staging -> prod webhook migration — no network, no
 * filesystem, so they can be unit tested.
 *
 * The app itself never creates products or prices: donations are ad-hoc
 * amounts carrying `metadata.churchId` on ONE platform account (docs/STRIPE.md).
 * So "migrate to prod" is exactly: register the same webhook endpoint on the
 * prod account and produce the prod env values.
 */

export const STRIPE_WEBHOOK_PATH = '/api/v1/webhooks/stripe'

/** Events the app forwards/expects (docs/STRIPE.md, package.json `stripe:listen`). */
export const REQUIRED_WEBHOOK_EVENTS = [
  'payment_intent.succeeded',
  'payment_intent.payment_failed',
  'checkout.session.completed',
  'customer.subscription.created',
  'customer.subscription.updated',
  'customer.subscription.deleted',
  'charge.succeeded',
  'charge.failed',
  'charge.refunded',
  'invoice.payment_succeeded',
  'invoice.payment_failed',
]

/** Stripe refuses an endpoint with more than this many events. */
export const MAX_WEBHOOK_EVENTS = 16

export type KeyMode = 'test' | 'live'

export const keyMode = (key: string): KeyMode | null => {
  const trimmed = key.trim()
  if (/^(sk|rk)_test_[A-Za-z0-9_]+$/.test(trimmed)) return 'test'
  if (/^(sk|rk)_live_[A-Za-z0-9_]+$/.test(trimmed)) return 'live'
  return null
}

export const assertKeyMode = (label: string, key: string, expected: KeyMode): void => {
  const mode = keyMode(key)
  if (!mode) {
    throw new Error(
      `${label} is not a Stripe secret key (expected sk_test_… / sk_live_…, got "${key.slice(0, 3)}…")`,
    )
  }
  if (mode !== expected) {
    throw new Error(`${label} is a ${mode} key, expected a ${expected} key — refusing to continue`)
  }
}

/** Trailing slash and host case must not create a duplicate endpoint. */
export const normalizeEndpointUrl = (url: string): string => {
  const trimmed = url.trim()
  try {
    const parsed = new URL(trimmed)
    const path = parsed.pathname.replace(/\/+$/, '')
    return `${parsed.protocol}//${parsed.host.toLowerCase()}${path}${parsed.search}`
  } catch {
    return trimmed.replace(/\/+$/, '')
  }
}

export interface WebhookEndpointLike {
  id: string
  url: string
  enabled_events?: string[]
  status?: string
}

export const findEndpoint = <T extends WebhookEndpointLike>(
  endpoints: T[],
  url: string,
): T | undefined =>
  endpoints.find((endpoint) => normalizeEndpointUrl(endpoint.url) === normalizeEndpointUrl(url))

/** Required events the target endpoint does not listen to yet. */
export const missingEvents = (
  enabled: string[] = [],
  required: string[] = REQUIRED_WEBHOOK_EVENTS,
): string[] => required.filter((event) => !enabled.includes(event))

/** Union of required + inherited events, de-duplicated, order stable. */
export const mergeEvents = (
  inherited: string[] = [],
  required: string[] = REQUIRED_WEBHOOK_EVENTS,
): string[] => {
  const merged: string[] = []
  for (const event of [...required, ...inherited]) {
    if (!merged.includes(event)) merged.push(event)
  }
  return merged
}

export const maskSecret = (value: string): string =>
  value.length <= 12 ? '*'.repeat(value.length || 3) : `${value.slice(0, 8)}…${value.slice(-4)}`

export interface ProdEnvValues {
  secretKey: string
  webhookSecret: string
  accountId: string
}

/** Env block written to `.hermes/stripe/…` — the four values prod needs. */
export const buildProdEnvBlock = ({ secretKey, webhookSecret, accountId }: ProdEnvValues): string =>
  [
    '# Stripe PROD (live) values — generated by src/script/stripe-migrate-prod.ts',
    '# Copy into .env.prod, then run: bun run env:sync --target production --file .env.prod',
    'STRIPE_ENABLED=true',
    `STRIPE_SECRET_KEY=${secretKey}`,
    `STRIPE_WEBHOOK_SECRET=${webhookSecret}`,
    `STRIPE_PLATFORM_ACCOUNT_ID=${accountId}`,
    '',
  ].join('\n')
